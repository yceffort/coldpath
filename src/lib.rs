/// Spread of a count over the runs of a repeated recording.
#[derive(Debug, Default, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Spread {
    pub min: usize,
    pub max: usize,
    pub mean: f64,
    /// Sample standard deviation over the runs.
    pub stddev: f64,
}

impl Spread {
    fn new(values: &[usize]) -> Self {
        let n = values.len() as f64;
        let mean = values.iter().sum::<usize>() as f64 / n;
        let variance = if values.len() > 1 {
            values
                .iter()
                .map(|&v| (v as f64 - mean).powi(2))
                .sum::<f64>()
                / (n - 1.0)
        } else {
            0.0
        };
        Self {
            min: values.iter().copied().min().unwrap_or_default(),
            max: values.iter().copied().max().unwrap_or_default(),
            mean,
            stddev: variance.sqrt(),
        }
    }

    fn varies(&self) -> bool {
        self.min != self.max
    }
}

#[derive(Debug, Default, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RunSpread {
    pub observed_bytes: Spread,
    pub unobserved_bytes: Spread,
    pub unmeasured_bytes: Spread,
}

impl RunSpread {
    fn new<'a>(counts: impl Iterator<Item = &'a Counts>) -> Self {
        let (mut observed, mut unobserved, mut unmeasured) = (Vec::new(), Vec::new(), Vec::new());
        for c in counts {
            observed.push(c.observed_bytes);
            unobserved.push(c.unobserved_bytes);
            unmeasured.push(c.unmeasured_bytes);
        }
        Self {
            observed_bytes: Spread::new(&observed),
            unobserved_bytes: Spread::new(&unobserved),
            unmeasured_bytes: Spread::new(&unmeasured),
        }
    }

    /// How far observed and unmeasured bytes move between runs.
    pub fn range(&self) -> usize {
        (self.observed_bytes.max - self.observed_bytes.min)
            + (self.unmeasured_bytes.max - self.unmeasured_bytes.min)
    }
}

