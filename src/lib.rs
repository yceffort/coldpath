/// Summary output keeps at most this many diagnostics per bundle; `--details` keeps all.
pub const SUMMARY_MAPPING_DIAGNOSTICS: usize = 100;

fn is_zero(value: &usize) -> bool {
    *value == 0
}

impl Report {
    fn limit_mapping_diagnostics(&mut self) {
        for bundle in &mut self.bundles {
            let total = bundle.mapping_diagnostics.len();
            if total <= SUMMARY_MAPPING_DIAGNOSTICS {
                continue;
            }
            bundle
                .mapping_diagnostics
                .truncate(SUMMARY_MAPPING_DIAGNOSTICS);
            bundle.omitted_mapping_diagnostics += total - SUMMARY_MAPPING_DIAGNOSTICS;
            for source in &mut bundle.sources {
                source
                    .mapping_diagnostics
                    .retain(|&index| index < SUMMARY_MAPPING_DIAGNOSTICS);
            }
            self.warnings.push(format!(
                "{}: summary lists the first {SUMMARY_MAPPING_DIAGNOSTICS} of {} mapping diagnostics; use --details for all",
                bundle.path, bundle.rejected_mappings
            ));
        }
        self.warnings.sort();
        self.warnings.dedup();
    }

    pub fn strip_details(&mut self) {
        self.limit_mapping_diagnostics();
        self.details = false;
        for bundle in &mut self.bundles {
            bundle.generated_source.clear();
            bundle.spans.clear();
            bundle.scenario_spans.clear();
            for source in &mut bundle.sources {
                source.content = None;
            }
        }
    }
}

pub fn sha256(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

/// Symlinks are not followed: one inside the root only aliases a real file or directory, so its
/// bytes would count twice. A link that could hide a bundle is skipped with a warning.
fn javascript_files(
    dir: &Path,
    paths: &mut Vec<PathBuf>,
    warnings: &mut Vec<String>,
) -> Result<()> {
    for entry in fs::read_dir(dir).with_context(|| format!("read {}", dir.display()))? {
        let entry = entry?;
        let kind = entry.file_type()?;
        let javascript = matches!(
            entry.path().extension().and_then(|ext| ext.to_str()),
            Some("js" | "mjs" | "cjs")
        );
        if kind.is_dir() {
            javascript_files(&entry.path(), paths, warnings)?;
        } else if kind.is_file() && javascript {
            paths.push(entry.path());
        } else if kind.is_symlink() && (javascript || !entry.path().is_file()) {
            // Named like a bundle, or pointing at a directory or at nothing.
            warnings.push(format!(
                "skipped symlink {} -> {}: coldpath scans only real files and directories inside the analysis root, so coverage must use the real path",
                entry.path().display(),
                fs::read_link(entry.path())?.display()
            ));
        }
    }
    Ok(())
}

pub fn analyze(dir: &Path, coverage_files: &[PathBuf]) -> Result<Report> {
    analyze_with_options(dir, coverage_files, &AnalyzeOptions::default())
}

pub fn analyze_with_options(
    dir: &Path,
    coverage_files: &[PathBuf],
    options: &AnalyzeOptions,
) -> Result<Report> {
    let canonical_root = fs::canonicalize(dir)?;
    if options.diff {
        ensure!(
            coverage_files.len() == 2 && options.input.scenario_names.len() == 2,
            "a recording diff takes exactly two coverage files and their names"
        );
    }
    let input::Loaded {
        index: mut coverage,
        mut scenarios,
        mut warnings,
        recording_warnings,
        mut prefetched,
        runs,
    } = input::load(coverage_files, dir, &options.input)?;
    // Scripts whose prefetch-only evidence the analyzer decided on, by scenario.
    let mut prefetch_left_out: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut prefetch_kept: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut run_counts: BTreeMap<String, BTreeMap<u32, RunAccumulator>> = BTreeMap::new();
    // Per bundle: path, bytes, recorded in A, recorded in B.
    let mut diff_measured: Vec<(String, usize, bool, bool)> = Vec::new();
    let mut diff_ranges: Vec<DiffBundleRanges> = Vec::new();
    let mut profiles = cpu::Profiles::load(&options.profiles)?;
    let mut seen = BTreeSet::new();
    scenarios.retain(|name| seen.insert(name.clone()));
    if !options.scenario_order.is_empty() {
        ensure!(
            options.scenario_order.len() == scenarios.len()
                && options.scenario_order.iter().collect::<BTreeSet<_>>()
                    == scenarios.iter().collect(),
            "--scenario-order must list every scenario exactly once; received {:?}, recorded {scenarios:?}",
            options.scenario_order
        );
        scenarios.clone_from(&options.scenario_order);
    }
    if let Some(initial) = &options.initial_scenario {
        ensure!(
            scenarios.contains(initial),
            "unknown initial scenario {initial:?}; available scenarios: {scenarios:?}"
        );
        if options.scenario_order.is_empty() {
            scenarios.retain(|name| name != initial);
            scenarios.insert(0, initial.clone());
        } else {
            ensure!(
                scenarios.first() == Some(initial),
                "--initial-scenario must be first in --scenario-order"
            );
        }
    }
    let mut scenario_reports = scenarios
        .iter()
        .cloned()
        .map(scenario::Accumulator::new)
        .collect::<Vec<_>>();
    let mut files = Vec::new();
    if let Some(selected) = &options.files {
        for path in selected {
            coverage::validate_path(&path.to_string_lossy())?;
            let file = dir.join(path);
            ensure!(
                file.is_file(),
                "input file does not exist: {}",
                file.display()
            );
            ensure!(
                fs::canonicalize(&file)?.starts_with(fs::canonicalize(dir)?),
                "input file escapes analysis root: {}",
                file.display()
            );
            files.push(file);
        }
    } else {
        javascript_files(dir, &mut files, &mut warnings)?;
    }
    files.sort();
    files.dedup();
    ensure!(
        !files.is_empty(),
        "no JavaScript files in {}",
        dir.display()
    );
    let mut report = Report {
        baseline: None,
        schema_version: 3,
        details: options.details,
        metric: "utf8-generated-source-bytes",
        attribution: "mapping-to-next-mapping-on-same-line; remaining bytes unmapped",
        mode: if coverage_files.is_empty() {
            STATIC_MODE
        } else {
            COVERAGE_MODE
        },
        scenarios,
        initial_scenario: options.initial_scenario.clone(),
        scenario_reports: Vec::new(),
        source_paths: "analysis-root-relative; virtual URL dot components removed",
        totals: Counts::default(),
        initial_load: None,
        unmeasured: Unmeasured::default(),
        unmapped: Unmapped::default(),
        runs: Vec::new(),
        recording_diff: None,
        bundles: Vec::new(),
        sources: Vec::new(),
        packages: Vec::new(),
        groups: Vec::new(),
        warnings,
        recording_warnings,
        excluded_bundles: Vec::new(),
        include: options.include.clone(),
        exclude: options.exclude.clone(),
        compression: options.compression.then(ci::CompressedSizes::default),
        budget_failures: Vec::new(),
        compression_settings: options.compression.then_some("gzip level=6 (flate2 zlib-rs backend); Brotli quality=5 lgwin=22; independent whole files"),
        source_compression_method: options.source_compression.then_some("isolated attributed fragments in generated order per source per bundle; non-additive estimates, not measured transfer savings"),
        import_paths: None,
        recommendations: Vec::new(),
        cpu: None,
        label_generator: None,
        read_files: Vec::new(),
        initial_execution: BTreeMap::new(),
    };
    for path in options.maps.keys() {
        coverage::validate_path(path)?;
        ensure!(
            files.iter().any(|file| file
                .strip_prefix(dir)
                .is_ok_and(|p| p.to_string_lossy().replace('\\', "/") == *path)),
            "explicit map references file missing from selected inputs: {path}"
        );
    }
    let mut source_counts: BTreeMap<String, Counts> = BTreeMap::new();
    let include = ci::globs(&options.include)?;
    let exclude = ci::globs(&options.exclude)?;
    for file in files {
        let path = file.strip_prefix(dir)?.to_string_lossy().replace('\\', "/");
        report.read_files.push(file.clone());
        if (!options.include.is_empty() && !include.is_match(&path)) || exclude.is_match(&path) {
            coverage.remove(&path);
            profiles.exclude(&path);
            report.excluded_bundles.push(path);
            continue;
        }
        let content =
            fs::read_to_string(&file).with_context(|| format!("read UTF-8 source {path}"))?;
        let text = TextIndex::new(&content);
        let hash = sha256(content.as_bytes());
        let map_data = maps::load_with_location(&file, &content, dir, options.maps.get(&path))
            .with_context(|| format!("locate source map for {path}"))?;
        let source_map_path = map_data.as_ref().and_then(|map| map.path.clone());
        let (segments, map_hash, mut sources, rejected) = if let Some(map) = map_data {
            report.read_files.extend(map.path.clone());
            let attribution::IndexedAttribution {
                segments,
                rejected,
                sources,
            } = attribution::decode_indexed(
                &map.data,
                &text,
                content.len(),
                options.details,
                Some(&source_path::SourcePaths {
                    root: &canonical_root,
                    directory: &map.directory,
                }),
            )
            .with_context(|| format!("decode source map for {path}"))?;
            if !rejected.is_empty() {
                report.warnings.push(format!("{path}: ignored {} mapping points outside their line or inside a surrogate pair; attribution is approximate (see mappingDiagnostics)", rejected.len()));
            }
            (segments, Some(sha256(&map.data)), sources, rejected)
        } else {
            report
                .warnings
                .push(format!("{path}: no source map; entire source is unmapped"));
            (
                vec![IndexedSegment {
                    start: 0,
                    end: content.len(),
                    source: 0,
                    original: None,
                }],
                None,
                vec![IndexedSource {
                    name: UNMAPPED.into(),
                    content: None,
                }],
                Vec::new(),
            )
        };
        profiles.bind(&path, &hash, &map_hash, &text, &segments, &sources)?;
        // Bundler wrappers (webpack's runtime IIFE, module factories) map to no source.
        // Turbopack factories and Rolldown's CommonJS wrappers have no mapping at their
        // start, so the previous module's last mapping claims it, while the wrapper's
        // own code maps to another source.
        let module_scope = |root: &coverage::CoverageRange| {
            text.byte(root.start_offset).is_ok_and(|byte| {
                let index = segments.partition_point(|s| s.end <= byte);
                segments.get(index).is_some_and(|s| {
                    s.source == 0
                        || s.start < byte
                            && text.byte(root.end_offset).is_ok_and(|end| {
                                segments[index + 1..]
                                    .iter()
                                    .take_while(|next| next.start < end)
                                    .find(|next| next.source != 0)
                                    .is_some_and(|next| next.source != s.source)
                            })
                })
            })
        };
        let mut observations = coverage.remove(&path);
        let mut verification = Vec::new();
        if let Some(list) = &mut observations {
            let mut kept = Vec::new();
            for observation in list.drain(..) {
                let binding = observation.verify(
                    &path,
                    &content,
                    &hash,
                    &map_hash,
                    options.input.allow_unverified,
                )?;
                if binding.source == "unverified" || binding.source_map == "unverified" {
                    report.warnings.push(format!("{path}: {} verification: source={}, source-map={}; current file hashes do not prove capture-time identity", observation.scenario, binding.source, binding.source_map));
                }
                // A script that only router prefetches for other routes loaded is left out when
                // nothing beyond module evaluation ran: the top level, wrappers, their blocks, and
                // functions of generated code such as webpack's chunk runtime callback or Next's
                // page entry, which run as the chunk loads. Generated code has no mapping of its
                // own: the previous module's last mapping claims it, whichever module that is.
                // Without a source map every function looks like a wrapper, so such a script stays.
                if let Some(routes) = &observation.prefetch_routes {
                    // Generated code: no mapping of its own, or a start that a virtual source claims
                    // (webpack's route entry maps into the next module's preamble).
                    let generated = |root: &coverage::CoverageRange| {
                        text.byte(root.start_offset).is_ok_and(|start| {
                            text.byte(root.end_offset).is_ok_and(|end| {
                                let index = segments.partition_point(|s| s.end <= start);
                                segments.get(index).is_some_and(|s| {
                                    attribution::is_virtual(&sources[s.source].name)
                                }) || !segments[segments.partition_point(|s| s.start < start)..]
                                    .iter()
                                    .take_while(|s| s.start < end)
                                    .any(|s| !attribution::is_virtual(&sources[s.source].name))
                            })
                        })
                    };
                    let evaluation_only = match observation
                        .function_used(&text, |root| module_scope(root) || generated(root))
                        .with_context(|| format!("normalize coverage for {path}"))?
                    {
                        Some((ranges, _)) if map_hash.is_some() => {
                            let used = coverage::union(ranges)
                                .into_iter()
                                .map(|range| {
                                    Ok(Interval {
                                        start: text.byte(range.start)?,
                                        end: text.byte(range.end)?,
                                    })
                                })
                                .collect::<Result<Vec<_>>>()?;
                            let mut cursor = 0;
                            !segments.iter().any(|segment| {
                                !attribution::is_virtual(&sources[segment.source].name)
                                    && scenario::overlap(segment, &used, &mut cursor) > 0
                            })
                        }
                        _ => false,
                    };
                    let entry = if evaluation_only {
                        let scenarios = prefetched.entry(path.clone()).or_default();
                        if !scenarios.contains(&observation.scenario) {
                            scenarios.push(observation.scenario.clone());
                        }
                        prefetch_left_out.entry(observation.scenario.clone())
                    } else {
                        prefetch_kept.entry(observation.scenario.clone())
                    };
                    entry
                        .or_default()
                        .push(format!("{path} ({})", routes.join(", ")));
                    if evaluation_only {
                        continue;
                    }
                }
                verification.push(binding);
                kept.push(observation);
            }
            *list = kept;
            if list.is_empty() {
                observations = None;
            }
        }
        let mut used = Vec::new();
        let mut scenario_used: BTreeMap<String, Vec<Interval>> = BTreeMap::new();
        let mut run_used: BTreeMap<(String, u32), Vec<Interval>> = BTreeMap::new();
        let mut initial_function_used = Some((Vec::new(), Vec::new()));
        if let Some(observations) = &observations {
            for observation in observations {
                if let input::Ranges::V8(functions) = &observation.ranges
                    && functions.iter().any(|function| {
                        !function.is_block_coverage
                            && function.ranges.iter().any(|range| range.count > 0)
                    })
                {
                    report.warnings.push(format!("{path}: executed function has function-only coverage; block detail unavailable"));
                }
                let ranges = observation
                    .used(&text)
                    .with_context(|| format!("normalize coverage for {path}"))?;
                if options.initial_scenario.as_ref() == Some(&observation.scenario) {
                    initial_function_used = match (
                        initial_function_used,
                        observation.function_used(&text, |root| module_scope(root))?,
                    ) {
                        (Some((mut all, mut scopes)), Some((ranges, wrappers))) => {
                            all.extend(ranges);
                            scopes.extend(wrappers);
                            Some((all, scopes))
                        }
                        _ => None,
                    };
                }
                used.extend_from_slice(&ranges);
                if let Some(run) = observation.run {
                    run_used
                        .entry((observation.scenario.clone(), run))
                        .or_default()
                        .extend_from_slice(&ranges);
                }
                scenario_used
                    .entry(observation.scenario.clone())
                    .or_default()
                    .extend(ranges);
            }
        }
        let used = coverage::union(used);
        let used_utf16 = used.iter().map(|range| range.end - range.start).sum();
        let used: Vec<Interval> = used
            .into_iter()
            .map(|range| {
                Ok(Interval {
                    start: text.byte(range.start)?,
                    end: text.byte(range.end)?,
                })
            })
            .collect::<Result<_>>()?;
        for ranges in scenario_used.values_mut().chain(run_used.values_mut()) {
            *ranges = coverage::union(std::mem::take(ranges))
                .into_iter()
                .map(|range| {
                    Ok(Interval {
                        start: text.byte(range.start)?,
                        end: text.byte(range.end)?,
                    })
                })
                .collect::<Result<_>>()?;
        }
        // Per-run counts of repeated recordings: a run that did not load the bundle leaves it unmeasured.
        for (scenario, numbers) in runs.iter().filter(|(_, numbers)| numbers.len() > 1) {
            for &run in numbers {
                let entry = run_counts
                    .entry(scenario.clone())
                    .or_default()
                    .entry(run)
                    .or_default();
                let observed = run_used.get(&(scenario.clone(), run));
                let mut cursor = 0;
                for segment in &segments {
                    let bytes = segment.end - segment.start;
                    let counts = match observed {
                        Some(observed) => {
                            let observed_bytes = scenario::overlap(segment, observed, &mut cursor);
                            Counts {
                                bytes,
                                observed_bytes,
                                unobserved_bytes: bytes - observed_bytes,
                                unmeasured_bytes: 0,
                            }
                        }
                        None => Counts {
                            bytes,
                            unmeasured_bytes: bytes,
                            ..Default::default()
                        },
                    };
                    entry.totals.add(&counts);
                    entry
                        .sources
                        .entry(sources[segment.source].name.clone())
                        .or_default()
                        .add(&counts);
                }
            }
        }
        if options.diff {
            let [a, b] = [0, 1].map(|i| scenario_used.get(&options.input.scenario_names[i]));
            diff_measured.push((path.clone(), content.len(), a.is_some(), b.is_some()));
            if let (Some(a), Some(b), true) = (a, b, options.details) {
                let attribute = |ranges: Vec<Interval>| {
                    let mut result = Vec::new();
                    for range in ranges {
                        for segment in &segments[segments.partition_point(|s| s.end <= range.start)
                            ..segments.partition_point(|s| s.start < range.end)]
                        {
                            result.push(DiffRange {
                                start: range.start.max(segment.start),
                                end: range.end.min(segment.end),
                                source: sources[segment.source].name.clone(),
                            });
                        }
                    }
                    result
                };
                let only_a = attribute(scenario::difference(a, b));
                let only_b = attribute(scenario::difference(b, a));
                if !only_a.is_empty() || !only_b.is_empty() {
                    diff_ranges.push(DiffBundleRanges {
                        path: path.clone(),
                        only_a,
                        only_b,
                    });
                }
            }
        }
        if let Some(initial_used) = options
            .initial_scenario
            .as_ref()
            .and_then(|name| scenario_used.get(name))
        {
            let (function_used, mut boundaries) = match initial_function_used {
                Some((ranges, scopes)) => (
                    coverage::union(ranges)
                        .into_iter()
                        .map(|range| {
                            Ok(Interval {
                                start: text.byte(range.start)?,
                                end: text.byte(range.end)?,
                            })
                        })
                        .collect::<Result<Vec<_>>>()?,
                    scopes
                        .iter()
                        .flat_map(|scope| [scope.start, scope.end])
                        .map(|offset| text.byte(offset))
                        .collect::<Result<Vec<_>>>()?,
                ),
                None => (initial_used.clone(), Vec::new()),
            };
            boundaries.sort_unstable();
            let top_level = scenario::difference(initial_used, &function_used);
            let (mut function_cursor, mut top_level_cursor, mut boundary) = (0, 0, 0);
            for segment in &segments {
                // A mapping owns bytes up to the next mapping, which can run past a module
                // wrapper into the next module; those bytes are not this source's execution.
                while boundaries
                    .get(boundary)
                    .is_some_and(|&b| b <= segment.start)
                {
                    boundary += 1;
                }
                let segment = &IndexedSegment {
                    end: boundaries
                        .get(boundary)
                        .map_or(segment.end, |&b| b.min(segment.end)),
                    ..*segment
                };
                let function_bytes =
                    scenario::overlap(segment, &function_used, &mut function_cursor);
                scenario::overlap(segment, &top_level, &mut top_level_cursor);
                let ranges = top_level[top_level_cursor..]
                    .iter()
                    .take_while(|range| range.start < segment.end);
                if function_bytes == 0 && ranges.clone().next().is_none() {
                    continue;
                }
                let entry = report
                    .initial_execution
                    .entry(sources[segment.source].name.clone())
                    .or_default();
                entry.function_bytes += function_bytes;
                for range in ranges {
                    entry.top_level.extend_from_slice(
                        &content.as_bytes()
                            [range.start.max(segment.start)..range.end.min(segment.end)],
                    );
                }
            }
        }
        for scenario in &mut scenario_reports {
            scenario.bundle(
                &path,
                &segments,
                &sources,
                &scenario_used,
                options.initial_scenario.as_deref(),
                options.source_compression.then_some(content.as_bytes()),
                prefetched.get(&path).map(Vec::as_slice),
            )?;
        }
        let phases =
            scenario::first_observed(&report.scenarios, &segments, sources.len(), &scenario_used);
        let estimates = if options.source_compression {
            let mut fragments = vec![Vec::new(); sources.len()];
            for segment in &segments {
                fragments[segment.source]
                    .extend_from_slice(&content.as_bytes()[segment.start..segment.end]);
            }
            fragments
                .iter()
                .map(|bytes| ci::compress(bytes).map(Some))
                .collect::<Result<Vec<_>>>()?
        } else {
            vec![None; sources.len()]
        };
        let mut counts = Counts::default();
        let mut mapped_bytes = 0;
        let mut used_index = 0;
        let mut bundle_sources: Vec<BundleSource> = Vec::new();
        let mut source_indices = vec![None; sources.len()];
        let mut spans = Vec::new();
        for segment in &segments {
            let source_index = if let Some(index) = source_indices[segment.source] {
                index
            } else {
                let source = &mut sources[segment.source];
                let index = bundle_sources.len();
                bundle_sources.push(BundleSource {
                    source: source.name.clone(),
                    package: attribution::package(&source.name),
                    content: source.content.take(),
                    first_observed: phases[segment.source].clone(),
                    estimated_compression: estimates[segment.source].clone(),
                    label: None,
                    rejected_mappings: 0,
                    mapping_diagnostics: Vec::new(),
                    counts: Counts::default(),
                });
                source_indices[segment.source] = Some(index);
                index
            };
            let bytes = segment.end - segment.start;
            while used_index < used.len() && used[used_index].end <= segment.start {
                used_index += 1;
            }
            let observed_bytes = used[used_index..]
                .iter()
                .take_while(|range| range.start < segment.end)
                .map(|range| {
                    range
                        .end
                        .min(segment.end)
                        .saturating_sub(range.start.max(segment.start))
                })
                .sum();
            let row = Counts {
                bytes,
                observed_bytes,
                unobserved_bytes: if observations.is_some() {
                    bytes - observed_bytes
                } else {
                    0
                },
                unmeasured_bytes: if observations.is_none() { bytes } else { 0 },
            };
            if segment.source != 0 {
                mapped_bytes += bytes;
            }
            bundle_sources[source_index].counts.add(&row);
            counts.add(&row);
            if options.details {
                let mut cursor = segment.start;
                let mut append = |start: usize, end: usize, status: Status| -> Result<()> {
                    if start < end {
                        spans.push(Span {
                            start,
                            end,
                            start_utf16: text.utf16(start)?,
                            end_utf16: text.utf16(end)?,
                            source: source_index,
                            status,
                            original: segment.original,
                        });
                    }
                    Ok(())
                };
                if observations.is_none() {
                    append(cursor, segment.end, Status::Unmeasured)?;
                } else {
                    for range in used[used_index..]
                        .iter()
                        .take_while(|r| r.start < segment.end)
                    {
                        let start = range.start.max(segment.start);
                        let end = range.end.min(segment.end);
                        append(cursor, start, Status::Unobserved)?;
                        append(start, end, Status::Observed)?;
                        cursor = end;
                    }
                    append(cursor, segment.end, Status::Unobserved)?;
                }
            }
        }
        ensure!(
            counts.bytes == content.len(),
            "{path}: source attribution lost bytes"
        );
        for source in &bundle_sources {
            source_counts
                .entry(source.source.clone())
                .or_default()
                .add(&source.counts);
        }
        let mut mapping_diagnostics = Vec::with_capacity(rejected.len());
        for (index, rejection) in rejected.iter().enumerate() {
            let (start, end) = (rejection.start, rejection.end);
            let overlapping = if start < end {
                &segments[segments.partition_point(|s| s.end <= start)
                    ..segments.partition_point(|s| s.start < end)]
            } else {
                &[]
            };
            let mut linked: Vec<usize> = overlapping
                .iter()
                .map(|s| s.source)
                .chain([rejection.mapping.source])
                .filter_map(|source| source_indices[source])
                .collect();
            linked.sort_unstable();
            linked.dedup();
            for source in linked {
                bundle_sources[source].rejected_mappings += 1;
                bundle_sources[source].mapping_diagnostics.push(index);
            }
            let describe = |mapping: &attribution::Mapping| MappingRef {
                generated_line: mapping.generated.0,
                generated_column: mapping.generated.1,
                source: sources[mapping.source].name.clone(),
                original: mapping.original,
            };
            mapping_diagnostics.push(MappingDiagnostic {
                reason: rejection.reason,
                mapping: describe(&rejection.mapping),
                previous: rejection.previous.as_ref().map(describe),
                next: rejection.next.as_ref().map(describe),
                inspect_region: Region {
                    start,
                    end,
                    start_utf16: text.utf16(start)?,
                    end_utf16: text.utf16(end)?,
                },
                assignments: overlapping
                    .iter()
                    .map(|s| Assignment {
                        start: s.start.max(start),
                        end: s.end.min(end),
                        source: sources[s.source].name.clone(),
                    })
                    .collect(),
            });
        }
        report.totals.add(&counts);
        let compression = if options.compression {
            Some(ci::compress(content.as_bytes())?)
        } else {
            None
        };
        if let (Some(total), Some(bundle)) = (&mut report.compression, &compression) {
            total.gzip_bytes += bundle.gzip_bytes;
            total.brotli_bytes += bundle.brotli_bytes;
        }
        report.bundles.push(BundleRow {
            path,
            sha256: hash,
            source_map_sha256: map_hash,
            utf16_units: text.utf16_len(),
            observed_utf16_units: observations.as_ref().map(|_| used_utf16),
            mapped_bytes,
            verification,
            generated_source: if options.details {
                content
            } else {
                String::new()
            },
            sources: bundle_sources,
            spans,
            scenario_spans: if options.details {
                report
                    .scenarios
                    .iter()
                    .map(|name| {
                        Ok((
                            name.clone(),
                            scenario::spans(
                                &segments,
                                scenario_used.get(name).map(Vec::as_slice),
                                &source_indices,
                                &text,
                            )?,
                        ))
                    })
                    .collect::<Result<_>>()?
            } else {
                BTreeMap::new()
            },
            compression,
            loading: None,
            rejected_mappings: rejected.len(),
            mapping_diagnostics,
            omitted_mapping_diagnostics: 0,
            counts,
            source_map_path,
        });
    }
    ensure!(
        !report.bundles.is_empty(),
        "no JavaScript files selected by --include/--exclude"
    );
    if options.files.is_some() && !coverage.is_empty() {
        let root = fs::canonicalize(dir)?;
        coverage.retain(|path, _| {
            let file = dir.join(path);
            // Keep missing/outside paths as errors: a wrong URL prefix must not
            // silently turn selected bundles into unmeasured code.
            if file.is_file() && fs::canonicalize(&file).is_ok_and(|file| file.starts_with(&root)) {
                report
                    .warnings
                    .push(format!("skipped coverage for unselected file: {path}"));
                false
            } else {
                true
            }
        });
    }
    ensure!(
        coverage.is_empty(),
        "coverage references files missing from analysis root {}: {:?}; check --dir, --url-prefix, or --script-map",
        dir.display(),
        coverage.keys().collect::<Vec<_>>()
    );
    // Like coverage: profiled files that exist but were not selected are skipped, missing ones fail.
    for path in profiles.pending() {
        let file = dir.join(&path);
        if options.files.is_some()
            && file.is_file()
            && fs::canonicalize(&file).is_ok_and(|file| file.starts_with(&canonical_root))
        {
            report
                .warnings
                .push(format!("skipped profile data for unselected file: {path}"));
            // Evidence export copies it, so a replay finds it unselected again.
            report.read_files.push(file);
            profiles.exclude(&path);
        }
    }
    let pending = profiles.pending();
    ensure!(
        pending.is_empty(),
        "profiles reference files missing from analysis root {}: {pending:?}; check --dir and the scenario prefix",
        dir.display()
    );
    report.cpu = profiles.finish()?;
    for (scenario, scripts) in prefetch_left_out {
        report.recording_warnings.push(format!(
            "{scenario}: the analyzer left out {} scripts that only router prefetches for other routes loaded and in which only module evaluation ran, so their bytes count as unmeasured: {}",
            scripts.len(),
            shown(&scripts)
        ));
    }
    for (scenario, scripts) in prefetch_kept {
        report.recording_warnings.push(format!(
            "{scenario}: kept {} scripts that only router prefetches for other routes loaded, because functions in them ran: {}",
            scripts.len(),
            shown(&scripts)
        ));
    }
    for (scenario, per_run) in run_counts {
        let accumulators = per_run.values().collect::<Vec<_>>();
        let mut package_counts: BTreeMap<String, Vec<Counts>> = BTreeMap::new();
        let mut source_counts: BTreeMap<&str, Vec<&Counts>> = BTreeMap::new();
        for accumulator in &accumulators {
            let mut packages: BTreeMap<String, Counts> = BTreeMap::new();
            for (source, counts) in &accumulator.sources {
                packages
                    .entry(attribution::package(source))
                    .or_default()
                    .add(counts);
                source_counts.entry(source).or_default().push(counts);
            }
            for (package, counts) in packages {
                package_counts.entry(package).or_default().push(counts);
            }
        }
        let mut packages = package_counts
            .into_iter()
            .map(|(package, counts)| PackageSpread {
                package,
                spread: RunSpread::new(counts.iter()),
            })
            .collect::<Vec<_>>();
        packages.sort_by(|a, b| {
            b.spread
                .range()
                .cmp(&a.spread.range())
                .then(a.package.cmp(&b.package))
        });
        let mut varying_sources = source_counts
            .into_iter()
            .map(|(source, counts)| SourceSpread {
                source: source.into(),
                package: attribution::package(source),
                spread: RunSpread::new(counts.into_iter()),
            })
            .filter(|row| {
                row.spread.observed_bytes.varies() || row.spread.unmeasured_bytes.varies()
            })
            .collect::<Vec<_>>();
        varying_sources.sort_by(|a, b| {
            b.spread
                .range()
                .cmp(&a.spread.range())
                .then(a.source.cmp(&b.source))
        });
        report.runs.push(RunReport {
            scenario,
            runs: accumulators.len(),
            totals: RunSpread::new(accumulators.iter().map(|a| &a.totals)),
            packages,
            varying_sources,
        });
    }
    for bundle in &report.bundles {
        if bundle.source_map_sha256.is_none() {
            report.unmapped.bundles_without_map += 1;
            report.unmapped.bytes_without_map += bundle.counts.bytes;
        } else if bundle.counts.bytes > bundle.mapped_bytes {
            report.unmapped.bundles_with_gaps += 1;
            report.unmapped.gap_bytes += bundle.counts.bytes - bundle.mapped_bytes;
        }
        if bundle.observed_utf16_units.is_some() {
            continue;
        }
        let scenarios = prefetched.get(&bundle.path).cloned().unwrap_or_default();
        let reason = if scenarios.is_empty() {
            report.unmeasured.not_recorded_bytes += bundle.counts.bytes;
            UnmeasuredReason::NotRecorded
        } else {
            report.unmeasured.prefetch_only_bytes += bundle.counts.bytes;
            UnmeasuredReason::PrefetchOnly
        };
        report.unmeasured.bundles.push(UnmeasuredBundle {
            path: bundle.path.clone(),
            bytes: bundle.counts.bytes,
            reason,
            scenarios,
        });
    }
    report.unmapped.bytes = report.unmapped.bytes_without_map + report.unmapped.gap_bytes;
    report.unmeasured.bytes = report.totals.unmeasured_bytes;
    sort_unmeasured(&mut report.unmeasured.bundles);
    if let Some(html) = &options.initial_html {
        report.initial_load = Some(initial_load(html, &report.bundles)?);
        if report.initial_load.as_ref().unwrap().bundles.is_empty() {
            report.warnings.push(format!(
                "--initial-html {} names none of the analyzed bundles; the initial load is empty. Check that the document references bundles under the analysis root.",
                html.display()
            ));
        }
    }
    (report.sources, report.packages) = aggregate_sources(source_counts);
    let mut copies: BTreeMap<&str, (usize, usize)> = BTreeMap::new();
    for source in report.bundles.iter().flat_map(|bundle| &bundle.sources) {
        if source.source != UNMAPPED {
            let entry = copies.entry(&source.source).or_default();
            entry.0 += 1;
            entry.1 = entry.1.max(source.counts.bytes);
        }
    }
    let copies = copies
        .into_iter()
        .filter(|(_, (bundles, _))| *bundles > 1)
        .map(|(source, copies)| (source.to_owned(), copies))
        .collect::<BTreeMap<_, _>>();
    for source in &mut report.sources {
        if let Some(&(bundles, largest)) = copies.get(&source.source) {
            source.duplicates = Some(Duplicates {
                bundles,
                extra_bytes: source.counts.bytes - largest,
            });
        }
    }
    if options.source_compression {
        let mut estimates: BTreeMap<String, ci::CompressedSizes> = BTreeMap::new();
        let mut packages: BTreeMap<String, ci::CompressedSizes> = BTreeMap::new();
        for source in report.bundles.iter().flat_map(|bundle| &bundle.sources) {
            if let Some(estimate) = &source.estimated_compression {
                estimates
                    .entry(source.source.clone())
                    .or_default()
                    .add(estimate);
                packages
                    .entry(source.package.clone())
                    .or_default()
                    .add(estimate);
            }
        }
        for source in &mut report.sources {
            source.estimated_compression = estimates.remove(&source.source);
        }
        for package in &mut report.packages {
            package.estimated_compression = packages.remove(&package.package);
        }
    }
    report.scenario_reports = scenario_reports
        .into_iter()
        .map(scenario::Accumulator::finish)
        .collect();
    if options.diff {
        let counts = |index: usize| {
            report.scenario_reports[index]
                .sources
                .iter()
                .map(|row| (row.source.as_str(), &row.counts))
                .collect::<BTreeMap<_, _>>()
        };
        let (a, b) = (counts(0), counts(1));
        let mut sources = a
            .keys()
            .chain(b.keys())
            .collect::<BTreeSet<_>>()
            .into_iter()
            .filter_map(|source| {
                let (before, after) = (
                    a.get(source).copied().cloned().unwrap_or_default(),
                    b.get(source).copied().cloned().unwrap_or_default(),
                );
                (before != after).then(|| DiffSource {
                    source: (*source).into(),
                    package: attribution::package(source),
                    delta: baseline::Delta {
                        bytes: after.bytes as i128 - before.bytes as i128,
                        observed_bytes: after.observed_bytes as i128
                            - before.observed_bytes as i128,
                        unobserved_bytes: after.unobserved_bytes as i128
                            - before.unobserved_bytes as i128,
                        unmeasured_bytes: after.unmeasured_bytes as i128
                            - before.unmeasured_bytes as i128,
                    },
                    a: before,
                    b: after,
                })
            })
            .collect::<Vec<_>>();
        sources.sort_by(|x, y| {
            y.delta
                .observed_bytes
                .abs()
                .cmp(&x.delta.observed_bytes.abs())
                .then(x.source.cmp(&y.source))
        });
        let only = |in_a: bool| {
            diff_measured
                .iter()
                .filter(|(_, _, a, b)| if in_a { *a && !*b } else { *b && !*a })
                .map(|(path, bytes, _, _)| DiffBundle {
                    path: path.clone(),
                    bytes: *bytes,
                })
                .collect::<Vec<_>>()
        };
        report.recording_diff = Some(RecordingDiff {
            a: coverage_files[0].to_string_lossy().replace('\\', "/"),
            b: coverage_files[1].to_string_lossy().replace('\\', "/"),
            only_a: only(true),
            only_b: only(false),
            sources,
            bundles: diff_ranges,
        });
    }
    report.recommendations = recommendations::build(&report);
    if !options.details {
        report.limit_mapping_diagnostics();
    }
    report.warnings.sort();
    report.warnings.dedup();
    Ok(report)
}

/// The first three of a list, with a count of the rest.
fn shown(items: &[String]) -> String {
    let mut text = items.iter().take(3).cloned().collect::<Vec<_>>().join(", ");
    if items.len() > 3 {
        text += ", ...";
    }
    text
}

pub(crate) fn sort_unmeasured(bundles: &mut [UnmeasuredBundle]) {
    bundles.sort_by(|a, b| b.bytes.cmp(&a.bytes).then(a.path.cmp(&b.path)));
}

/// Why a bundle is unmeasured, for summaries.
pub fn unmeasured_reason(bundle: &UnmeasuredBundle) -> String {
    match bundle.reason {
        UnmeasuredReason::NotRecorded => "no scenario loaded it".into(),
        UnmeasuredReason::PrefetchOnly => format!(
            "left out: only router prefetches for other routes loaded it ({})",
            bundle.scenarios.join(", ")
        ),
    }
}

/// The selected bundles a document names: a bundle's analysis-root-relative path appears in the
/// HTML as a whole path suffix, so `/_next/static/chunks/a.js` names `chunks/a.js`, as is or with
/// each segment encoded the way Next.js writes it (`app/%5Bslug%5D/page.js`). Script tags,
/// preload links, and references inside inline scripts (such as an RSC payload) all count.
fn initial_load(html: &Path, bundles: &[BundleRow]) -> Result<InitialLoad> {
    // What JavaScript's encodeURIComponent leaves unencoded.
    const URI_COMPONENT: &percent_encoding::AsciiSet = &percent_encoding::NON_ALPHANUMERIC
        .remove(b'-')
        .remove(b'_')
        .remove(b'.')
        .remove(b'!')
        .remove(b'~')
        .remove(b'*')
        .remove(b'\'')
        .remove(b'(')
        .remove(b')');
    let text = String::from_utf8_lossy(
        &fs::read(html).with_context(|| format!("read --initial-html {}", html.display()))?,
    )
    .into_owned();
    let boundary = |c: Option<char>| {
        c.is_none_or(|c| !(c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '-')))
    };
    let mut bytes = 0;
    let mut named = Vec::new();
    for bundle in bundles {
        let path = bundle.path.as_str();
        let encoded = path
            .split('/')
            .map(|segment| {
                percent_encoding::utf8_percent_encode(segment, URI_COMPONENT).to_string()
            })
            .collect::<Vec<_>>()
            .join("/");
        if std::iter::once(path)
            .chain((encoded != path).then_some(encoded.as_str()))
            .any(|path| {
                text.match_indices(path).any(|(at, _)| {
                    boundary(text[..at].chars().next_back())
                        && boundary(text[at + path.len()..].chars().next())
                })
            })
        {
            bytes += bundle.counts.bytes;
            named.push(bundle.path.clone());
        }
    }
    Ok(InitialLoad {
        html: html.to_string_lossy().replace('\\', "/"),
        bytes,
        bundles: named,
    })
}

/// Groups sources by the shortest leading part of their path that a pattern matches, trying the
/// patterns in order. `*` does not cross `/`; `**` does. Unmatched sources belong to no group.
pub fn group_sources(report: &mut Report, patterns: &[String]) -> Result<()> {
    let globs = patterns
        .iter()
        .map(|pattern| {
            globset::GlobBuilder::new(pattern)
                .literal_separator(true)
                .build()
                .map(|glob| glob.compile_matcher())
                .with_context(|| format!("invalid --group-by glob {pattern:?}"))
        })
        .collect::<Result<Vec<_>>>()?;
    let mut groups: BTreeMap<&str, GroupRow> = BTreeMap::new();
    for source in &report.sources {
        let name = source.source.as_str();
        let prefixes = || {
            name.match_indices('/')
                .map(|(end, _)| &name[..end])
                .chain([name])
        };
        let Some((group, pattern)) = globs.iter().zip(patterns).find_map(|(glob, pattern)| {
            prefixes()
                .find(|prefix| glob.is_match(prefix))
                .map(|prefix| (prefix, pattern))
        }) else {
            continue;
        };
        let row = groups.entry(group).or_insert_with(|| GroupRow {
            group: group.into(),
            pattern: pattern.clone(),
            sources: 0,
            estimated_compression: None,
            counts: Counts::default(),
        });
        row.sources += 1;
        row.counts.add(&source.counts);
        if let Some(estimate) = &source.estimated_compression {
            row.estimated_compression
                .get_or_insert_with(Default::default)
                .add(estimate);
        }
    }
    let mut groups = groups.into_values().collect::<Vec<_>>();
    groups.sort_by(|a, b| {
        b.counts
            .bytes
            .cmp(&a.counts.bytes)
            .then(a.group.cmp(&b.group))
    });
    report.groups = groups;
    Ok(())
}

fn aggregate_sources(source_counts: BTreeMap<String, Counts>) -> (Vec<SourceRow>, Vec<PackageRow>) {
    let mut sources = Vec::new();
    let mut packages: BTreeMap<String, Counts> = BTreeMap::new();
    for (source, counts) in source_counts {
        let package = attribution::package(&source);
        packages.entry(package.clone()).or_default().add(&counts);
        sources.push(SourceRow {
            source,
            package,
            estimated_compression: None,
            label: None,
            duplicates: None,
            counts,
        });
    }
    sources.sort_by(|a, b| {
        b.counts
            .bytes
            .cmp(&a.counts.bytes)
            .then(a.source.cmp(&b.source))
    });
    let mut packages: Vec<_> = packages
        .into_iter()
        .map(|(package, counts)| PackageRow {
            package,
            counts,
            estimated_compression: None,
            importers: None,
        })
        .collect();
    packages.sort_by(|a, b| {
        b.counts
            .bytes
            .cmp(&a.counts.bytes)
            .then(a.package.cmp(&b.package))
    });
    (sources, packages)
}
